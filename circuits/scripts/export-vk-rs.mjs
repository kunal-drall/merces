#!/usr/bin/env node
// Converts a snarkjs verification_key.json into a Rust module holding a
// `groth16_solana::groth16::Groth16Verifyingkey` (groth16-solana 0.2.0).
//
// Byte conventions follow the crate's own `parse_vk_to_rust.js`:
//   * G1 points: x ‖ y, each a 32-byte big-endian field element.
//   * G2 points: x.c1 ‖ x.c0 ‖ y.c1 ‖ y.c0 (imaginary part first, as the EVM precompiles and
//     snarkjs' Solidity verifier order them), each 32-byte big-endian.
//   * `nr_pubinputs` is the number of IC points (= public inputs + 1), exactly as the crate's
//     generator writes it; the verifier itself only uses `vk_ic.len()`.
//
// Usage: node export-vk-rs.mjs <verification_key.json> <out.rs>
import { readFileSync, writeFileSync } from "node:fs";

const [, , vkPath, outPath] = process.argv;
if (!vkPath || !outPath) {
  console.error("usage: export-vk-rs.mjs <verification_key.json> <out.rs>");
  process.exit(2);
}
const vk = JSON.parse(readFileSync(vkPath, "utf8"));
if (vk.protocol !== "groth16" || vk.curve !== "bn128") {
  throw new Error(`unexpected vk: protocol=${vk.protocol} curve=${vk.curve}`);
}

const Q = 21888242871839275222246405745257275088696311157297823662689037894645226208583n;

function be32(dec) {
  const v = BigInt(dec);
  if (v < 0n || v >= Q) throw new Error(`coordinate out of range: ${dec}`);
  const out = new Array(32);
  let x = v;
  for (let i = 31; i >= 0; i--) {
    out[i] = Number(x & 0xffn);
    x >>= 8n;
  }
  return out;
}
function g1(p) {
  if (p[2] !== "1") throw new Error("G1 point not in affine form");
  return [...be32(p[0]), ...be32(p[1])];
}
function g2(p) {
  if (p[2][0] !== "1" || p[2][1] !== "0") throw new Error("G2 point not in affine form");
  // snarkjs stores each Fp2 coordinate as [c0, c1]; on-chain order is c1 ‖ c0.
  return [...be32(p[0][1]), ...be32(p[0][0]), ...be32(p[1][1]), ...be32(p[1][0])];
}

function rustArray(bytes, indent) {
  const pad = " ".repeat(indent);
  const lines = [];
  for (let i = 0; i < bytes.length; i += 16) {
    lines.push(pad + bytes.slice(i, i + 16).join(", ") + ",");
  }
  return lines.join("\n");
}

const nPublic = vk.IC.length - 1;
if (nPublic !== vk.nPublic) throw new Error(`IC length ${vk.IC.length} does not match nPublic ${vk.nPublic}`);

let s = "";
s += "//! Groth16 verifying key for the Merces ProofOfIncome report circuit (`circuits/src/report.circom`).\n";
s += "//!\n";
s += "//! GENERATED by `circuits/scripts/build.sh` from `circuits/build/verification_key.json`. Do not edit.\n";
s += "//! The key comes from the DEVELOPMENT-ONLY trusted setup described in `circuits/README.md`;\n";
s += "//! it is not for production.\n";
s += "//!\n";
s += "//! Encoding (groth16-solana 0.2.0, see its `parse_vk_to_rust.js`): every field element is 32-byte\n";
s += "//! big-endian; G1 = x ‖ y; G2 = x.c1 ‖ x.c0 ‖ y.c1 ‖ y.c0. Public inputs, in order:\n";
s += "//! `[terms_commitment, units_outstanding, fx_avg_wad, prior_income_commitment, income_commitment, payment_usd]`.\n";
s += "//! Proofs must be passed with `pi_a` negated (see `circuits/README.md`, \"Proof encoding\").\n";
s += "\n";
s += "use groth16_solana::groth16::Groth16Verifyingkey;\n\n";
s += "/// Number of public inputs of the report circuit.\n";
s += `pub const NR_PUBLIC_INPUTS: usize = ${nPublic};\n\n`;
s += "/// Verifying key. `nr_pubinputs` follows the crate generator's convention (number of IC points =\n";
s += "/// public inputs + 1); the verifier uses `vk_ic.len()` and ignores this field.\n";
s += "pub const VERIFYING_KEY: Groth16Verifyingkey = Groth16Verifyingkey {\n";
s += `    nr_pubinputs: ${vk.IC.length},\n\n`;
s += "    vk_alpha_g1: [\n" + rustArray(g1(vk.vk_alpha_1), 8) + "\n    ],\n\n";
s += "    vk_beta_g2: [\n" + rustArray(g2(vk.vk_beta_2), 8) + "\n    ],\n\n";
s += "    vk_gamme_g2: [\n" + rustArray(g2(vk.vk_gamma_2), 8) + "\n    ],\n\n";
s += "    vk_delta_g2: [\n" + rustArray(g2(vk.vk_delta_2), 8) + "\n    ],\n\n";
s += "    vk_ic: &[\n";
for (const ic of vk.IC) {
  s += "        [\n" + rustArray(g1(ic), 12) + "\n        ],\n";
}
s += "    ],\n";
s += "};\n";
writeFileSync(outPath, s);
console.log(`wrote ${outPath} (${nPublic} public inputs, ${vk.IC.length} IC points)`);
