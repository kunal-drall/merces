#!/usr/bin/env bash
# Regenerates evm/test/utils/Proofs.sol: genuine Groth16 proofs for the ProofOfIncome circuit (circuits/build,
# development zkey) over fixed witnesses. Run from anywhere: `bash evm/scripts/proofs/run.sh`.
# Terms: theta 80,000 USDC/yr (80e9 at 6 decimals), r = 0.1 % per unit (1e15 WAD), currency 840 (fxQ1: 978 at
# fx 1.1), indexing 0, terms salt 11111. The `t1*` proofs use income/prior salt 0 (pure tier-1 series, SPEC §1.5).
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
OUT="${PROOFS_OUT:-$HERE/out}"
mkdir -p "$OUT"
gen() { node "$HERE/gen.mjs" "$@" > "$OUT/$1.json"; }
# name        theta       rWad             units fxWad               incomeYtd    priorIncomeYtd currency indexing termsSalt incomeSalt priorSalt
gen q1        80000000000 1000000000000000 300 1000000000000000000 120000000000 0            840 0 11111 22222 0 &
gen q2        80000000000 1000000000000000 300 1000000000000000000 160000000000 120000000000 840 0 11111 33333 22222 &
gen q3zero    80000000000 1000000000000000 300 1000000000000000000 160000000000 160000000000 840 0 11111 44444 33333 &
gen q4        80000000000 1000000000000000 300 1000000000000000000 300000000000 160000000000 840 0 11111 55555 44444 &
wait
gen y2q1      80000000000 1000000000000000 300 1000000000000000000 100000000000 0            840 0 11111 66666 0 &
gen y2q2cap   80000000000 1000000000000000 300 1000000000000000000 200000000000 100000000000 840 0 11111 77777 66666 &
gen belowTheta 80000000000 1000000000000000 300 1000000000000000000 50000000000 0            840 0 11111 88888 0 &
gen fxQ1      80000000000 1000000000000000 300 1100000000000000000 120000000000 0            978 0 11111 99999 0 &
wait
gen units299  80000000000 1000000000000000 299 1000000000000000000 120000000000 0            840 0 11111 22222 0 &
gen big       80000000000 1000000000000000 300 1000000000000000000 400000000000 0            840 0 11111 12121 0 &
gen tail      80000000000 1000000000000000 300 1000000000000000000 500000000000 0            840 0 11111 13131 0 &
gen tinyCap   80000000000 1000000000000000 300 1000000000000000000 80000000001 0             840 0 11111 14141 0 &
wait
gen t1q1      80000000000 1000000000000000 300 1000000000000000000 120000000000 0            840 0 11111 0 0 &
gen t1q2      80000000000 1000000000000000 300 1000000000000000000 160000000000 120000000000 840 0 11111 0 0 &
wait
python3 "$HERE/to-sol.py" "$OUT" "$HERE/../../test/utils/Proofs.sol"
