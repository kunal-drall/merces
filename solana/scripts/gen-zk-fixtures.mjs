#!/usr/bin/env node
// Generates the Solana-side ZK artefacts from a Groth16 report-circuit build (SPEC §8):
//
//   1. `programs/merces_protocol/src/zk/vk.rs` — the verifying key in `groth16-solana` layout
//      (big-endian coordinates, G2 as x_im ‖ x_re ‖ y_im ‖ y_re), and
//   2. `tests/fixtures/zk/report_fixtures.json` — proofs for the scenarios the LiteSVM tests drive,
//      already in the 256-byte on-chain proof layout (A negated: x ‖ q − y, as the vectors do).
//
// Usage:
//   node gen-zk-fixtures.mjs --build <dir with report_final.zkey, verification_key.json, report_js/report.wasm>
//                            [--vk-out <path>] [--fixtures-out <path>] [--skip-vk]
//
// The default build dir is `circuits/build` (Track A's reference circuit). Until it exists, pass
// Track B's scratch build. Development setups only; never for production (see circuits/README).

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import * as snarkjs from "snarkjs";
import { buildPoseidon } from "circomlibjs";

const here = dirname(fileURLToPath(import.meta.url));
const args = Object.fromEntries(
  process.argv.slice(2).reduce((acc, a, i, arr) => {
    if (a.startsWith("--")) acc.push([a.slice(2), arr[i + 1] && !arr[i + 1].startsWith("--") ? arr[i + 1] : "true"]);
    return acc;
  }, []),
);
const buildDir = resolve(args.build ?? resolve(here, "../../circuits/build"));
const vkOut = resolve(args["vk-out"] ?? resolve(here, "../programs/merces_protocol/src/zk/vk.rs"));
const fixturesOut = resolve(args["fixtures-out"] ?? resolve(here, "../tests/fixtures/zk/report_fixtures.json"));

const zkeyPath = resolve(buildDir, "report_final.zkey");
const vkPath = resolve(buildDir, "verification_key.json");
const wasmPath = resolve(buildDir, "report_js/report.wasm");
for (const p of [zkeyPath, vkPath, wasmPath]) {
  if (!existsSync(p)) {
    console.error(`missing ${p}`);
    process.exit(1);
  }
}

const WAD = 10n ** 18n;
const be32 = (x) => BigInt(x).toString(16).padStart(64, "0");
const hex = (s) => "0x" + s;

// ---------------------------------------------------------------- verifying key → vk.rs
function g1Bytes(p) {
  return be32(p[0]) + be32(p[1]);
}
function g2Bytes(p) {
  // snarkjs: [[x_re, x_im], [y_re, y_im], [1, 0]] → EIP-197 / alt_bn128 order: x_im, x_re, y_im, y_re
  return be32(p[0][1]) + be32(p[0][0]) + be32(p[1][1]) + be32(p[1][0]);
}
function rustArray(hexStr, indent) {
  const bytes = hexStr.match(/../g).map((b) => parseInt(b, 16));
  const lines = [];
  for (let i = 0; i < bytes.length; i += 16) lines.push(indent + bytes.slice(i, i + 16).join(", ") + ",");
  return lines.join("\n");
}
const vk = JSON.parse(readFileSync(vkPath, "utf8"));
if (vk.protocol !== "groth16" || vk.curve !== "bn128") throw new Error("expected a groth16/bn128 verification key");
if (vk.nPublic !== 6) throw new Error(`expected 6 public inputs, got ${vk.nPublic}`);
const vkHash = createHash("sha256").update(readFileSync(vkPath)).digest("hex");
if (args["skip-vk"] !== "true") {
  const ic = vk.IC.map((p) => `    [\n${rustArray(g1Bytes(p), "        ")}\n    ],`).join("\n");
  const rs = `//! Groth16 verifying key for the ProofOfIncome report circuit (SPEC §8), generated by
//! \`solana/scripts/gen-zk-fixtures.mjs\` from \`verification_key.json\`
//! (sha256 ${vkHash}).
//!
//! DEVELOPMENT CEREMONY — the zkey comes from a local powers-of-tau with fixed entropy and is not
//! for production. Regenerate this file whenever the circuit or the setup changes.
//!
//! Layout (groth16-solana): big-endian coordinates; G2 points as x_im ‖ x_re ‖ y_im ‖ y_re.

use groth16_solana::groth16::Groth16Verifyingkey;

pub const VERIFYINGKEY: Groth16Verifyingkey = Groth16Verifyingkey {
    nr_pubinputs: ${vk.nPublic},
    vk_alpha_g1: [
${rustArray(g1Bytes(vk.vk_alpha_1), "        ")}
    ],
    vk_beta_g2: [
${rustArray(g2Bytes(vk.vk_beta_2), "        ")}
    ],
    vk_gamme_g2: [
${rustArray(g2Bytes(vk.vk_gamma_2), "        ")}
    ],
    vk_delta_g2: [
${rustArray(g2Bytes(vk.vk_delta_2), "        ")}
    ],
    vk_ic: &[
${ic}
    ],
};
`;
  writeFileSync(vkOut, rs);
  console.log(`wrote ${vkOut}`);
}

// ---------------------------------------------------------------- scenarios
// Terms shared by the LiteSVM tests: 100 units, P0 = 1_000 USDC/unit, θ = 60_000 USD, r = 0.1%/unit
// (total share 10%). Amounts in 6-decimal USD minor units; fx = 1 (stablecoin income).
const poseidon = await buildPoseidon();
const F = poseidon.F;
const P = (xs) => F.toObject(poseidon(xs.map((x) => BigInt(x))));

const THETA = 60_000_000_000n; // 60k USD
const R_WAD = 1_000_000_000_000_000n; // 0.001
const CURRENCY = 840n;
const INDEXING = 0n;
const TERMS_SALT = 123456789n;
const UNITS = 100n;
const termsCommitment = P([THETA, R_WAD, CURRENCY, INDEXING, TERMS_SALT]);
const ZERO_INCOME = P([0n, 0n]);
const salt = (i) => 1000n + BigInt(i);

function owed(ytd, units) {
  const excess = ytd > THETA ? ytd - THETA : 0n;
  return (R_WAD * units * excess) / WAD;
}
function payment(prevYtd, ytd, units, fx = WAD) {
  return ((owed(ytd, units) - owed(prevYtd, units)) * fx) / WAD;
}

const scenarios = [];
function scenario(name, { prevYtd, prevSalt, ytd, incomeSalt, units = UNITS, fx = WAD, termsCommitmentOverride, note }) {
  const prior = prevYtd === null ? ZERO_INCOME : P([prevYtd, prevSalt]);
  const incomeCommitment = P([ytd, incomeSalt]);
  const pay = payment(prevYtd ?? 0n, ytd, units, fx);
  scenarios.push({
    name,
    note,
    input: {
      terms_commitment: (termsCommitmentOverride ?? termsCommitment).toString(),
      units_outstanding: units.toString(),
      fx_avg_wad: fx.toString(),
      prior_income_commitment: prior.toString(),
      income_commitment: incomeCommitment.toString(),
      payment_usd: pay.toString(),
      theta: THETA.toString(),
      r_wad: R_WAD.toString(),
      currency_code: CURRENCY.toString(),
      indexing_rule: INDEXING.toString(),
      terms_salt: TERMS_SALT.toString(),
      income_ytd: ytd.toString(),
      income_salt: incomeSalt.toString(),
      prior_income_ytd: (prevYtd ?? 0n).toString(),
      prior_salt: (prevSalt ?? 0n).toString(),
    },
  });
}

// Year 1: below threshold for two quarters, crossing in Q3 (checks the YTD method).
scenario("y1_q1", { prevYtd: null, prevSalt: null, ytd: 20_000_000_000n, incomeSalt: salt(1), note: "below threshold → payment 0" });
scenario("y1_q2", { prevYtd: 20_000_000_000n, prevSalt: salt(1), ytd: 45_000_000_000n, incomeSalt: salt(2), note: "still below → 0" });
scenario("y1_q3", { prevYtd: 45_000_000_000n, prevSalt: salt(2), ytd: 80_000_000_000n, incomeSalt: salt(3), note: "crosses: 0.1 × 20k = 2k" });
scenario("y1_q4", { prevYtd: 80_000_000_000n, prevSalt: salt(3), ytd: 120_000_000_000n, incomeSalt: salt(4), note: "0.1 × 40k = 4k" });
// Year 2: starts from the zero prior again; large Q1 income (cap-hit scenarios pay 100k+ in one quarter).
scenario("y2_q1_big", { prevYtd: null, prevSalt: null, ytd: 3_060_000_000_000n, incomeSalt: salt(5), note: "0.1 × 3M = 300k > remaining cap" });
scenario("y2_q1", { prevYtd: null, prevSalt: null, ytd: 100_000_000_000n, incomeSalt: salt(6), note: "0.1 × 40k = 4k" });
scenario("y2_q2", { prevYtd: 100_000_000_000n, prevSalt: salt(6), ytd: 150_000_000_000n, incomeSalt: salt(7), note: "0.1 × 50k = 5k" });
// Tail report after a redemption of all 100 units (units_outstanding := units_at_redemption).
scenario("tail_big", { prevYtd: null, prevSalt: null, ytd: 1_060_000_000_000n, incomeSalt: salt(8), note: "liquidity event: 0.1 × 1M = 100k" });
// Zero-income year start (payment 0, prior zero).
scenario("zero_year", { prevYtd: null, prevSalt: null, ytd: 0n, incomeSalt: salt(9), note: "zero income is a valid report" });
// Window / lockup tests report with 100 units, modest payment.
scenario("y3_q1", { prevYtd: null, prevSalt: null, ytd: 70_000_000_000n, incomeSalt: salt(10), note: "0.1 × 10k = 1k" });

// ---------------------------------------------------------------- prove
// BN254 base field modulus q.
const Q = 21888242871839275222246405745257275088696311157297823662689037894645226208583n;
function proofBytes(proof) {
  // A is negated (x ‖ q − y), matching packages/vectors `proofSolana.proofA`; the program verifies as-is.
  const ay = BigInt(proof.pi_a[1]);
  const a = be32(proof.pi_a[0]) + be32(ay === 0n ? 0n : Q - ay);
  const b = be32(proof.pi_b[0][1]) + be32(proof.pi_b[0][0]) + be32(proof.pi_b[1][1]) + be32(proof.pi_b[1][0]);
  const c = be32(proof.pi_c[0]) + be32(proof.pi_c[1]);
  return hex(a + b + c);
}
const out = {
  generated_from: { build_dir: buildDir, verification_key_sha256: vkHash },
  terms: {
    theta: THETA.toString(),
    r_wad: R_WAD.toString(),
    currency_code: CURRENCY.toString(),
    indexing_rule: INDEXING.toString(),
    terms_salt: TERMS_SALT.toString(),
    terms_commitment: hex(be32(termsCommitment)),
    zero_income_commitment: hex(be32(ZERO_INCOME)),
    units: UNITS.toString(),
  },
  fixtures: [],
};
for (const s of scenarios) {
  const { proof, publicSignals } = await snarkjs.groth16.fullProve(s.input, wasmPath, zkeyPath);
  const ok = await snarkjs.groth16.verify(vk, publicSignals, proof);
  if (!ok) throw new Error(`proof for ${s.name} does not verify`);
  const expected = [s.input.terms_commitment, s.input.units_outstanding, s.input.fx_avg_wad, s.input.prior_income_commitment, s.input.income_commitment, s.input.payment_usd];
  if (publicSignals.join(",") !== expected.join(",")) throw new Error(`public signal order mismatch for ${s.name}: ${publicSignals} vs ${expected}`);
  out.fixtures.push({
    name: s.name,
    note: s.note,
    public: {
      terms_commitment: hex(be32(s.input.terms_commitment)),
      units_outstanding: s.input.units_outstanding,
      fx_avg_wad: s.input.fx_avg_wad,
      prior_income_commitment: hex(be32(s.input.prior_income_commitment)),
      income_commitment: hex(be32(s.input.income_commitment)),
      payment_usd: s.input.payment_usd,
    },
    private: {
      income_ytd: s.input.income_ytd,
      income_salt: s.input.income_salt,
      prior_income_ytd: s.input.prior_income_ytd,
      prior_salt: s.input.prior_salt,
    },
    proof: proofBytes(proof),
    snarkjs: { proof, publicSignals },
  });
  console.log(`proved ${s.name}: payment_usd=${s.input.payment_usd}`);
}
mkdirSync(dirname(fixturesOut), { recursive: true });
writeFileSync(fixturesOut, JSON.stringify(out, null, 2) + "\n");
console.log(`wrote ${fixturesOut} (${out.fixtures.length} fixtures)`);
process.exit(0);
