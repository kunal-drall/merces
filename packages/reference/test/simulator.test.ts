import { describe, it, expect } from "vitest";
import { ScenarioBuilder, usdc, ts } from "../src/vectors/builder.js";
import { WAD } from "@merces/sdk";
import { Simulator } from "../src/sim/simulator.js";

describe("simulator (SPEC v1.1)", () => {
  it("raise with claims-based settlement, process/deliver, a zero report, a paid report and a claim; money and units are conserved", async () => {
    const b = new ScenarioBuilder("test_sim", "simulator smoke");
    b.key("attestor1", "attestor").key("verifier1", "verifier").actor("issuer", "b1", "b2");
    b.at(ts(2026, 1, 2));
    await b.step({ op: "register_attestor", key: "attestor1" });
    await b.step({ op: "register_verifier_key", key: "verifier1" });
    await b.step({ op: "allowlist", wallets: ["issuer", "b1", "b2"] });
    await b.step({ op: "register_issuer", wallet: "issuer" });
    for (const [a, amt] of [["issuer", 50_000], ["b1", 30_000], ["b2", 30_000]] as const) await b.fund(a, usdc(amt));
    const funded = b.sim.totalStable();
    await b.createSeries({ series: "S1", issuer: "issuer", plain: { theta: usdc(80_000), rWad: WAD / 10_000n, currencyCode: 840, indexingRule: 0 }, terms: { walletCapBps: 5000, minRaise: usdc(20_000) } });
    const p = await b.raise({ series: "S1", issuer: "issuer", openAt: ts(2026, 1, 5), bids: [{ actor: "b1", price: usdc(120), quantity: 100n }, { actor: "b2", price: usdc(110), quantity: 100n }], undelivered: ["b2"] });
    expect(p).toBe(usdc(110));
    const s = b.sim.series.get("S1")!;
    expect(s.auction.mintFinalized).toBe(true);
    expect(s.ledger.unitsOutstanding).toBe(200n);
    expect(s.auction.unitsSold).toBe(200n);
    expect(s.treasury.proceeds).toBe(usdc(22_000));
    expect(b.sim.feeCollector).toBe(usdc(220));
    expect(b.sim.unitsOf("b2", "S1")).toBe(0n); // undelivered
    expect(s.auction.escrowUnits).toBe(100n);
    expect(b.sim.accrualUnits(s, "b2")).toBe(100n);
    expect(b.sim.totalStable()).toBe(funded);
    b.sim.checkUnitSupply("S1");
    b.at(ts(2026, 4, 2));
    const q1 = await b.report({ series: "S1", period: 2026 * 4, incomeYtd: usdc(40_000), tier: 2 });
    expect(q1.paymentUsd).toBe(0n);
    expect(s.ledger.lastPaidPeriod).toBe(2026 * 4);
    b.at(ts(2026, 7, 3));
    const q2 = await b.report({ series: "S1", period: 2026 * 4 + 1, incomeYtd: usdc(130_000), tier: 2 });
    expect(q2.paymentUsd).toBe(usdc(1_000)); // 2% of (130k − 80k)
    await b.step({ op: "pay", actor: "issuer", series: "S1" });
    expect(s.vaultBalance).toBe(usdc(950));
    await b.step({ op: "claim", actor: "b1", series: "S1" });
    expect(b.sim.account("b1").stable).toBe(usdc(30_000) - usdc(11_110) + usdc(475));
    // the undelivered winner accrues on its pending units and can be delivered any time
    await b.step({ op: "deliver_bid", series: "S1", bidder: "b2" });
    expect(b.sim.unitsOf("b2", "S1")).toBe(100n);
    await b.step({ op: "claim", actor: "b2", series: "S1" });
    expect(b.sim.account("b2").stable).toBe(usdc(30_000) - usdc(11_110) + usdc(475));
    expect(b.sim.totalStable()).toBe(funded);
    b.sim.checkUnitSupply("S1");
    await b.revert({ op: "transfer_units", actor: "b1", series: "S1", to: "b2", units: "1" }, "DirectTransferForbidden");
    await b.revert({ op: "claim_release", actor: "b1", series: "S1" }, "NotIssuer");
    await b.step({ op: "claim_release", actor: "issuer", series: "S1" });
    expect(s.treasury.releasedTotal).toBe(usdc(11_000));
    const snap = b.expect("S1");
    expect(snap.ledger!.unitsOutstanding).toBe("200");
    expect(snap.ledger!.status).toBe("OnTime");
    expect(snap.auction!.mintFinalized).toBe(true);
    const v = b.build();
    expect(v.schema).toBe(2);
    const sim2 = new Simulator();
    await sim2.run(v.steps);
    expect(sim2.serialize()).toBe(b.sim.serialize());
  });

  it("settlement rounds: a wrong proposal is rejected (no revert) and a new one can follow; TallyInProgress blocks resets", async () => {
    const b = new ScenarioBuilder("test_rounds", "rounds");
    b.actor("issuer", "b1", "b2");
    b.at(ts(2026, 1, 2));
    await b.step({ op: "allowlist", wallets: ["issuer", "b1", "b2"] });
    await b.step({ op: "register_issuer", wallet: "issuer" });
    await b.fund("b1", usdc(30_000));
    await b.fund("b2", usdc(30_000));
    await b.createSeries({ series: "S1", issuer: "issuer", plain: { theta: usdc(80_000), rWad: WAD / 10_000n, currencyCode: 840, indexingRule: 0 }, terms: { walletCapBps: 5000 } });
    const s = b.sim.series.get("S1")!;
    b.at(ts(2026, 1, 5));
    await b.step({ op: "open_raise", actor: "issuer", series: "S1" });
    await b.step({ op: "commit_bid", actor: "b1", series: "S1", price: usdc(120).toString(), quantity: "100", salt: b.salt("1"), escrow: usdc(12_120).toString() });
    await b.step({ op: "commit_bid", actor: "b2", series: "S1", price: usdc(110).toString(), quantity: "100", salt: b.salt("2"), escrow: usdc(11_110).toString() });
    b.at(s.commitEnd + 1n);
    await b.step({ op: "reveal_bid", actor: "b1", series: "S1", price: usdc(120).toString(), quantity: "100", salt: b.salt("1") });
    await b.step({ op: "reveal_bid", actor: "b2", series: "S1", price: usdc(110).toString(), quantity: "100", salt: b.salt("2") });
    b.at(s.revealEnd);
    await b.step({ op: "begin_settlement", series: "S1", clearingPrice: usdc(120).toString(), qAboveClaim: "0", qAtClaim: "100" });
    await b.revert({ op: "begin_settlement", series: "S1", clearingPrice: usdc(110).toString(), qAboveClaim: "100", qAtClaim: "100" }, "TallyInProgress");
    await b.step({ op: "finalize_settlement", series: "S1" }, "120 is not the lowest valid price → rejected");
    expect(s.auction.roundRejected).toBe(true);
    expect(s.auction.rejectionReason).toBe("InvalidClearingPrice");
    await b.step({ op: "begin_settlement", series: "S1", clearingPrice: usdc(110).toString(), qAboveClaim: "100", qAtClaim: "99" });
    await b.step({ op: "finalize_settlement", series: "S1" }, "claims do not match the tally → rejected");
    expect(s.auction.rejectionReason).toBe("ClaimMismatch");
    await b.step({ op: "begin_settlement", series: "S1", clearingPrice: usdc(110).toString(), qAboveClaim: "100", qAtClaim: "100" });
    await b.step({ op: "finalize_settlement", series: "S1" });
    expect(s.auction.tallyRound).toBe(3);
    expect(s.auction.unitsSold).toBe(200n);
    await b.revert({ op: "claim_release", actor: "issuer", series: "S1" }, "MintNotFinalized");
    await b.revert({ op: "deliver_bid", series: "S1", bidder: "b1" }, "NotProcessed");
    await b.step({ op: "process_bid", series: "S1", bidder: "b1" });
    await b.step({ op: "process_bid", series: "S1", bidder: "b2" });
    expect(s.auction.mintFinalized).toBe(true);
    await b.step({ op: "deliver_bid", series: "S1", bidder: "b1" });
    await b.revert({ op: "deliver_bid", series: "S1", bidder: "b1" }, "AlreadyDelivered");
  });

  it("reverts leave the state untouched and name the right error", async () => {
    const b = new ScenarioBuilder("test_revert", "revert atomicity");
    b.actor("issuer", "b1");
    b.at(ts(2026, 1, 2));
    await b.step({ op: "allowlist", wallets: ["issuer", "b1"] });
    await b.step({ op: "register_issuer", wallet: "issuer" });
    await b.fund("b1", usdc(1_000));
    await b.createSeries({ series: "S1", issuer: "issuer", plain: { theta: usdc(80_000), rWad: WAD / 10_000n, currencyCode: 840, indexingRule: 0 }, contractHash: null });
    await b.revert({ op: "open_raise", actor: "issuer", series: "S1" }, "ContractHashMissing");
    await b.step({ op: "set_contract_hash", actor: "issuer", series: "S1", contractHash: b.salt("S1:contract") });
    await b.revert({ op: "commit_bid", actor: "b1", series: "S1", price: "1", quantity: "1", salt: b.salt("x"), escrow: "1" }, "RaiseNotOpen");
    await b.step({ op: "open_raise", actor: "issuer", series: "S1" });
    await b.revert({ op: "commit_bid", actor: "b1", series: "S1", price: "1", quantity: "1", salt: b.salt("x"), escrow: "0" }, "ZeroEscrow");
    await b.revert({ op: "commit_bid", actor: "nobody", series: "S1", price: "1", quantity: "1", salt: b.salt("x"), escrow: "1" }, "NotAllowlisted");
    await b.revert({ op: "commit_bid", actor: "b1", series: "S1", price: "1", quantity: "1", salt: b.salt("x"), escrow: (1n << 64n).toString() }, "AmountOutOfRange");
    await expect(b.revert({ op: "commit_bid", actor: "b1", series: "S1", price: "1", quantity: "1", salt: b.salt("x"), escrow: "1" }, "ZeroEscrow")).rejects.toThrow(/succeeded/);
    expect(b.sim.account("b1").stable).toBe(usdc(1_000) - 1n);
  });
});
