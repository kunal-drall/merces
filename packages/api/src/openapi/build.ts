/**
 * Assemble the deliverable contract: `packages/api/openapi.yaml` = base (`src/openapi/openapi.yaml`) + every
 * fragment in `src/openapi/fragments/*.yaml` (each contributes `paths`, and optionally `components` and `tags`).
 * Fragments let service modules own their operations without editing one shared file. Duplicate paths fail the build.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parse, stringify } from 'yaml';

const BASE = fileURLToPath(new URL('./openapi.yaml', import.meta.url));
const FRAGMENTS = fileURLToPath(new URL('./fragments/', import.meta.url));
export const BUILT = fileURLToPath(new URL('../../openapi.yaml', import.meta.url));

type Spec = { paths: Record<string, unknown>; components?: Record<string, Record<string, unknown>>; tags?: { name: string; description?: string }[] };

export function buildSpec(): Spec {
  const base = parse(readFileSync(BASE, 'utf8')) as Spec;
  const files = readdirSync(FRAGMENTS).filter((f) => f.endsWith('.yaml')).sort();
  for (const f of files) {
    const frag = parse(readFileSync(FRAGMENTS + f, 'utf8')) as Partial<Spec>;
    for (const [p, ops] of Object.entries(frag.paths ?? {})) {
      if (base.paths[p]) throw new Error(`fragment ${f}: path ${p} already defined`);
      base.paths[p] = ops;
    }
    for (const [section, items] of Object.entries(frag.components ?? {})) {
      base.components ??= {};
      base.components[section] ??= {};
      for (const [k, v] of Object.entries(items)) {
        if (base.components[section][k]) throw new Error(`fragment ${f}: components.${section}.${k} already defined`);
        base.components[section][k] = v;
      }
    }
    for (const t of frag.tags ?? []) if (!(base.tags ?? []).some((x) => x.name === t.name)) (base.tags ??= []).push(t);
  }
  return base;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const spec = buildSpec();
  writeFileSync(BUILT, '# GENERATED by `pnpm openapi:build` from packages/api/src/openapi/openapi.yaml + fragments/*.yaml — edit those, not this file.\n' + stringify(spec, { lineWidth: 0 }));
  console.log(`wrote ${BUILT} (${Object.keys(spec.paths).length} paths)`);
}
