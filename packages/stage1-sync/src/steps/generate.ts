import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { Stage1Location } from '@merces/chains';
import { stage1Path } from '@merces/chains';
import type { StepReport } from '../report.ts';

export interface StepCtx {
  location: Stage1Location;
  outDir: string;
  generatedDir: string;
  /** where the repository copy of INTERFACE_DRIFT.md is written (default: ./INTERFACE_DRIFT.md, the committed report) */
  driftFile?: string;
}

/**
 * Step 2: generate typed clients from the Solana IDLs and the EVM ABIs.
 * EVM: every ABI JSON becomes `export const <name>Abi = [...] as const` for viem.
 * Solana: every Anchor IDL becomes a typed module (instructions, accounts, events, types) through the
 * built-in IDL renderer (`idl-render.ts`); Codama can replace it once Stage 1 pins an IDL version.
 */
export async function generateClients(ctx: StepCtx): Promise<StepReport> {
  const details: string[] = [];
  let status: StepReport['status'] = 'ok';
  const m = ctx.location.manifest;

  const idlDir = stage1Path(ctx.location, m.solana?.idlDir);
  if (idlDir && existsSync(idlDir)) {
    const out = join(ctx.generatedDir, 'solana');
    mkdirSync(out, { recursive: true });
    const { renderAnchorIdl } = await import('../idl-render.ts');
    const names: string[] = [];
    for (const f of readdirSync(idlDir).filter((x) => !x.startsWith('.') && x.endsWith('.json'))) {
      try {
        const idl = JSON.parse(readFileSync(join(idlDir, f), 'utf8'));
        const name = f.replace(/\.json$/, '');
        writeFileSync(join(out, `${name}.ts`), renderAnchorIdl(name, idl));
        names.push(name);
      } catch (e) {
        status = 'fail';
        details.push(`[solana] IDL ${f}: ${(e as Error).message}`);
      }
    }
    writeFileSync(join(out, 'index.ts'), names.map((n) => `export * as ${n.replace(/[^a-zA-Z0-9_]/g, '_')} from './${n}.ts';`).join('\n') + '\n');
    details.push(`[solana] ${names.length} IDL(s) rendered to ${out}`);
  } else if (m.solana) {
    status = 'fail';
    details.push(`[solana] idlDir missing: ${m.solana.idlDir ?? '(unset)'} — blocker`);
  }

  for (const e of m.evm ?? []) {
    const abiDir = stage1Path(ctx.location, e.abiDir);
    if (!abiDir || !existsSync(abiDir)) {
      status = 'fail';
      details.push(`[${e.chain}] abiDir missing: ${e.abiDir ?? '(unset)'} — blocker`);
      continue;
    }
    const out = join(ctx.generatedDir, 'evm');
    mkdirSync(out, { recursive: true });
    const names: string[] = [];
    for (const f of readdirSync(abiDir).filter((x) => !x.startsWith('.') && x.endsWith('.json'))) {
      const raw = JSON.parse(readFileSync(join(abiDir, f), 'utf8'));
      const abi = Array.isArray(raw) ? raw : raw.abi;
      if (!Array.isArray(abi)) {
        status = 'fail';
        details.push(`[${e.chain}] ${f}: no ABI array found`);
        continue;
      }
      const name = f.replace(/\.json$/, '').replace(/[^a-zA-Z0-9_]/g, '_');
      writeFileSync(join(out, `${name}.ts`), `// generated by stage1:sync from ${f}\nexport const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`);
      names.push(name);
    }
    writeFileSync(join(out, 'index.ts'), names.map((n) => `export { ${n}Abi } from './${n}.ts';`).join('\n') + '\n');
    details.push(`[${e.chain}] ${names.length} ABI(s) rendered to ${out}`);
  }
  return { step: 'generate', status, summary: status === 'ok' ? 'typed clients generated' : 'generation incomplete', details };
}
