/**
 * Minimal Anchor IDL → TypeScript renderer. It produces: the program id, instruction names with argument
 * and account lists, account and event type definitions, and a discriminator table. It is deliberately
 * dependency-free; Codama (@codama/nodes-from-anchor + @codama/renderers-js) can replace it when Stage 1
 * pins an IDL spec version (see VERSIONS.md).
 */
interface IdlType {
  name?: string;
  type?: unknown;
}
interface IdlInstruction {
  name: string;
  discriminator?: number[];
  accounts?: { name: string; writable?: boolean; signer?: boolean; isMut?: boolean; isSigner?: boolean }[];
  args?: { name: string; type: unknown }[];
}
interface IdlEvent {
  name: string;
  discriminator?: number[];
}
interface AnchorIdl {
  address?: string;
  metadata?: { name?: string; version?: string; spec?: string };
  name?: string;
  version?: string;
  instructions?: IdlInstruction[];
  accounts?: IdlType[];
  events?: IdlEvent[];
  types?: { name: string; type: { kind: string; fields?: { name: string; type: unknown }[]; variants?: { name: string }[] } }[];
}

function tsType(t: unknown): string {
  if (typeof t === 'string') {
    switch (t) {
      case 'bool': return 'boolean';
      case 'u8': case 'i8': case 'u16': case 'i16': case 'u32': case 'i32': case 'f32': case 'f64': return 'number';
      case 'u64': case 'i64': case 'u128': case 'i128': case 'u256': case 'i256': return 'bigint';
      case 'string': return 'string';
      case 'pubkey': case 'publicKey': return 'string';
      case 'bytes': return 'Uint8Array';
      default: return 'unknown';
    }
  }
  if (t && typeof t === 'object') {
    const o = t as Record<string, unknown>;
    if ('option' in o) return `${tsType(o.option)} | null`;
    if ('vec' in o) return `${tsType(o.vec)}[]`;
    if ('array' in o && Array.isArray(o.array)) return `${tsType(o.array[0])}[]`;
    if ('defined' in o) {
      const d = o.defined as string | { name: string };
      return typeof d === 'string' ? d : d.name;
    }
  }
  return 'unknown';
}

export function renderAnchorIdl(moduleName: string, idl: AnchorIdl): string {
  const lines: string[] = [];
  const name = idl.metadata?.name ?? idl.name ?? moduleName;
  lines.push(`// generated by stage1:sync from Anchor IDL "${name}" (spec ${idl.metadata?.spec ?? 'legacy'}, version ${idl.metadata?.version ?? idl.version ?? '?'})`);
  lines.push(`export const programName = ${JSON.stringify(name)};`);
  lines.push(`export const programId = ${JSON.stringify(idl.address ?? null)};`);
  for (const t of idl.types ?? []) {
    if (t.type.kind === 'struct') {
      lines.push(`export interface ${t.name} {`);
      for (const f of t.type.fields ?? []) lines.push(`  ${f.name}: ${tsType(f.type)};`);
      lines.push('}');
    } else if (t.type.kind === 'enum') {
      lines.push(`export type ${t.name} = ${(t.type.variants ?? []).map((v) => JSON.stringify(v.name)).join(' | ') || 'never'};`);
    }
  }
  lines.push('export const instructions = {');
  for (const ix of idl.instructions ?? []) {
    lines.push(`  ${ix.name}: { discriminator: ${JSON.stringify(ix.discriminator ?? null)}, accounts: ${JSON.stringify((ix.accounts ?? []).map((a) => ({ name: a.name, writable: a.writable ?? a.isMut ?? false, signer: a.signer ?? a.isSigner ?? false })))}, args: ${JSON.stringify((ix.args ?? []).map((a) => ({ name: a.name, type: tsType(a.type) })))} },`);
  }
  lines.push('} as const;');
  lines.push('export const events = {');
  for (const ev of idl.events ?? []) lines.push(`  ${ev.name}: { discriminator: ${JSON.stringify(ev.discriminator ?? null)} },`);
  lines.push('} as const;');
  lines.push('export const accounts = {');
  for (const acc of idl.accounts ?? []) lines.push(`  ${acc.name}: { discriminator: ${JSON.stringify((acc as { discriminator?: number[] }).discriminator ?? null)} },`);
  lines.push('} as const;');
  return lines.join('\n') + '\n';
}
