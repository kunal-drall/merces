import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const spec = new URL('../../api/src/openapi/openapi.yaml', import.meta.url);
const out = fileURLToPath(new URL('./generated/openapi.d.ts', import.meta.url));
const ast = await openapiTS(spec, { exportType: true });
writeFileSync(out, '// generated by `pnpm openapi:client` from packages/api/src/openapi/openapi.yaml — do not edit\n' + astToString(ast));
console.log(`wrote ${out}`);
