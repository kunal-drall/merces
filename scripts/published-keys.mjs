#!/usr/bin/env node
// Public test fixtures only. The generated module contains addresses, never private keys.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';
import { addressFromPrivateKey, deriveTestPrivateKey } from '../stage1/packages/sdk/dist/index.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const addresses = new Set();
const seeds = new Set(['sim-attestor:attestor-1', 'sim-attestor:attestor-2', 'sim-verifier:verifier-1', 'merces-dev-attestor:1', 'merces-dev-attestor:2', 'merces-s4-dev:attestor-1', 'merces-s4-dev:attestor-2', 'merces-local-kms:dev-seed-not-for-production:report-verifier-1']);
const address = (key) => '0x' + Buffer.from(addressFromPrivateKey(key)).toString('hex');
function fixtures(value) {
  if (!value || typeof value !== 'object') return;
  if (typeof value.privateKey === 'string' && /^0x[0-9a-fA-F]{64}$/.test(value.privateKey)) addresses.add(address(Buffer.from(value.privateKey.slice(2), 'hex')));
  for (const entry of Object.values(value)) fixtures(entry);
}
function visit(dir) {
  for (const item of readdirSync(dir, { withFileTypes: true })) {
    if (item.name.startsWith('.') || ['node_modules', 'dist', 'target'].includes(item.name)) continue;
    const path = join(dir, item.name);
    if (item.isDirectory()) visit(path);
    else if (item.name.endsWith('.json')) fixtures(JSON.parse(readFileSync(path, 'utf8')));
    else if (item.name.endsWith('.ts')) {
      const src = readFileSync(path, 'utf8');
      for (const match of src.matchAll(/(?:new SimSigner|deriveTestPrivateKey)\(['"]([^'"\n]+)['"]\)/g)) seeds.add(match[1]);
      for (const match of src.matchAll(/SimSigner\.(attestor|verifier)\(['"]([^'"\n]+)['"]\)/g)) seeds.add(`sim-${match[1]}:${match[2]}`);
    }
  }
}
for (const dir of ['packages', 'stage1/packages', 'docs/stage1/defects/vectors']) visit(join(root, dir));
for (const seed of seeds) addresses.add(address(deriveTestPrivateKey(seed)));
const out = '// Generated by scripts/published-keys.mjs from published fixtures and literal simulator seeds. Addresses only.\n'
  + `const PUBLISHED_KEYS = new Set(${JSON.stringify([...addresses].sort(), null, 2)});\n\n`
  + '/** Known public development keys cannot be enrolled or imported for a live chain. */\n'
  + 'export function isPublishedTestKey(address: string): boolean { return PUBLISHED_KEYS.has(address.toLowerCase()); }\n';
const target = join(root, 'packages/domain/src/published-keys.ts');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== out) throw new Error('published key list is stale: node scripts/published-keys.mjs');
} else writeFileSync(target, out);
console.log(`published keys: ${addresses.size} addresses`);
